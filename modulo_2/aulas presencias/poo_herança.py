# =========================
# POO- Herança
# =========================

# Herança é um conceito da Programação Orientada a Objetos (POO) que permite que uma classe filha
# herde atributos e métodos de uma classe pai, facilitando o reaproveitamento de código.

# O método super() é usado para acessar métodos e atributos da classe pai dentro da classe filha.
# Exemplo de uso ao sobrescrever o método __str__:

# def __str__(self):
#     return f"Nome: {self.nome}, Idade: {self.idade},"

# def __str__(self):
#     return f"{super().__str__()}, Matrícula: {self.matricula}"

# Dessa forma, ao imprimir o objeto, todas as informações da classe pai e filha são exibidas automaticamente.

# Vantagens da herança:
# - Reutilização de código
# - Especialização de comportamentos
# - Facilidade de manutenção e extensão


